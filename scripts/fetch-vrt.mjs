// Downloads a VRT release from bugcrowd/vulnerability-rating-taxonomy and writes
// src/core/data/vrt.ts. Usage: node scripts/fetch-vrt.mjs [tag], such as v1.19.1.
// The VRT is licensed under Apache-2.0; see NOTICE.
import { writeFileSync } from 'node:fs';

const tag = process.argv[2] ?? 'v1.19.1';
if (!/^v\d+\.\d+(\.\d+)?$/.test(tag)) throw new Error(`Not a release tag: ${tag}`);
const base = `https://raw.githubusercontent.com/bugcrowd/vulnerability-rating-taxonomy/${tag}`;

async function get(file) {
  const res = await fetch(`${base}/${file}`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return res.json();
}

const vrt = await get('vulnerability-rating-taxonomy.json');
const deprecated = await get('deprecated-node-mapping.json');

// Keep only the fields the package uses, in a fixed order.
const strip = (node) => ({
  id: node.id,
  name: node.name,
  ...('priority' in node ? { priority: node.priority } : {}),
  ...(node.children ? { children: node.children.map(strip) } : {}),
});

const data = {
  version: tag.slice(1),
  releaseDate: vrt.metadata?.release_date?.slice(0, 10) ?? null,
  content: vrt.content.map(strip),
};

const out = `// Generated by scripts/fetch-vrt.mjs from bugcrowd/vulnerability-rating-taxonomy ${tag}.
// Don't edit by hand. The VRT is licensed under Apache-2.0; see NOTICE.
import type { VrtSource } from '../types';

export const VRT_DATA: VrtSource = ${JSON.stringify(data)};

export const VRT_DEPRECATED: Record<string, Record<string, string>> = ${JSON.stringify(deprecated)};
`;
writeFileSync(new URL('../src/core/data/vrt.ts', import.meta.url), out);
console.log(`Wrote VRT ${data.version} (${data.releaseDate}) with ${Object.keys(deprecated).length} deprecated IDs.`);
